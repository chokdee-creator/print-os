const assert=require('node:assert/strict');
const K=require('../knowledge.js');
const state=K.defaults();
const item=K.entry({title:'ตั้งค่าสี',url:'https://example.com/print',category:'printing',tags:'สี, ไวนิล, สี',favorite:true,note:'อ่านก่อนพิมพ์'},state.categories);
assert.deepEqual(item.tags,['สี','ไวนิล']);assert.equal(item.category,'printing');assert.equal(item.favorite,true);
for(const address of ['javascript:alert(1)','data:text/html,test','ftp://example.com/a','https://user:secret@example.com'])assert.throws(()=>K.url(address));
assert.equal(K.video('https://youtu.be/dQw4w9WgXcQ?t=30'),'https://www.youtube-nocookie.com/embed/dQw4w9WgXcQ');
assert.equal(K.video('https://youtube.com/shorts/dQw4w9WgXcQ'),'https://www.youtube-nocookie.com/embed/dQw4w9WgXcQ');
assert.equal(K.video('https://youtube.com.evil.example/watch?v=dQw4w9WgXcQ'),'');
assert.equal(K.video('https://vimeo.com/123456789'),'https://player.vimeo.com/video/123456789');
assert.equal(K.type('https://www.tiktok.com/@example/video/123'),'video');
assert.equal(K.type('https://example.com/readme'),'link');
const imported={version:1,categories:[{id:'new-print',name:'เทคนิคงานพิมพ์',color:K.colors[0]},{id:'new-cat',name:'หมวดใหม่',color:K.colors[1]}],entries:[{...item,id:'incoming',category:'new-print'},{...item,id:'incoming2',url:'https://example.com/second',category:'new-cat'}]};
state.entries.push(item);const merged=K.merge(state,imported);
assert.equal(merged.added,1);assert.equal(merged.data.entries.length,2);assert.equal(merged.data.categories.length,5);assert.equal(state.entries.length,1);
assert.equal(merged.data.categories.find(c=>c.id===merged.data.entries[1].category).name,'หมวดใหม่');
assert.throws(()=>K.validate({...imported,entries:[item,item]}));assert.throws(()=>K.validate({version:99,categories:[],entries:[]}));
assert.equal(K.entry({...item,category:'deleted'},state.categories).category,'');
console.log('PASS: knowledge validation, URL safety, video hosts, tags, category mapping, non-destructive backup merge and deduplication');
const note=K.entry({title:'พรอมต์พร้อมสรุป PDF',note:'เก็บความรู้โดยไม่ต้องมีลิงก์',category:'design'},state.categories);
assert.equal(note.url,'');assert.equal(note.type,'note');
assert.equal(K.entry({...item,url:'',type:'video'},state.categories).type,'note');
assert.equal(K.entry({...note,url:'https://example.com/guide'},state.categories).type,'link');
assert.equal(K.entry({...note,url:'https://youtu.be/dQw4w9WgXcQ'},state.categories).type,'video');
const notesBackup={version:1,categories:state.categories,entries:[note,{...note,id:'another-note',title:'โน้ตอีกเรื่อง'}]};
const notesRestored=K.merge(K.defaults(),notesBackup);
assert.equal(notesRestored.added,2);
assert.equal(K.merge(notesRestored.data,notesBackup).added,0);
assert.equal(K.validate(notesRestored.data).entries[0].note,note.note);
assert.throws(()=>K.entry({...note,url:'invalid-address'},state.categories));
console.log('PASS: note-only save, video without link becomes note, distinct notes survive backup and duplicate notes are skipped');
